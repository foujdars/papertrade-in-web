import { build } from 'esbuild';
import { mkdir, writeFile } from 'node:fs/promises';

// A single offline bundle is required: the sandbox deliberately cannot import
// scripts or fetch market data from the application's authenticated origin.
const result = await build({
  entryPoints: ['lib/pine-runtime.worker.ts'],
  bundle: true,
  write: false,
  platform: 'browser',
  format: 'iife',
  target: 'es2022',
  minify: true,
  legalComments: 'inline',
  define: { 'process.env.NODE_ENV': '"production"' },
});
await mkdir('lib/generated', { recursive: true });
await writeFile('lib/generated/pine-worker-source.ts',
  `// Generated by scripts/build-pine-runtime.mjs.\nexport default ${JSON.stringify(result.outputFiles[0].text)};\n`);
console.log('Built isolated Pine runtime.');
